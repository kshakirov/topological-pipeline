func TestDecoder(t *testing.T){
	payload := []byte{
		0x04, 0x01, 0x00, // DATA, Version, Flags
		0x12, 0x3e, 0x45, 0x67, 0xe8, 0x9b, 0x42, 0xd3, 0xa4, 0x56, 0x42, 0x66, 0x14, 0x17, 0x40, 0x00,
		0xf4, 0x7a, 0xc1, 0x0b, 0x58, 0xcc, 0x43, 0x72, 0xa5, 0x67, 0x0e, 0x02, 0xb2, 0xc3, 0xd4, 0x79,
		0x9b, 0x2a, 0xf9, 0xd0, 0x1e, 0x76, 0x4b, 0x8c, 0x8f, 0x67, 0xcc, 0xb0, 0xe3, 0x4e, 0x8c, 0x6a,
		0xAA,
	}
	result,err := Decoder(payload)
	if err != nil{
		t.Fatal("must not be error")
	}
	if len(result.Payload)!=1 || result.Payload[0]!= 0xAA {
		t.Fatal("must be of size 1")
	}
	
}

func TestEncoder(t *testing.T){
	msg := Message{
		RootId:    [16]byte{0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f, 0x10},
		MessageId: [16]byte{0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d, 0x1e, 0x1f, 0x20},
		ParentId:  [16]byte{0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x27, 0x28, 0x29, 0x2a, 0x2b, 0x2c, 0x2d, 0x2e, 0x2f, 0x30},
		Flags:     0x7f,
		Payload:   []byte{0xaa, 0xbb},
	}

	want := []byte{
		0x04, 0x01, 0x7f,
		0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f, 0x10,
		0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d, 0x1e, 0x1f, 0x20,
		0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x27, 0x28, 0x29, 0x2a, 0x2b, 0x2c, 0x2d, 0x2e, 0x2f, 0x30,
		0xaa, 0xbb,
	}

	if got := Encoder(msg); !bytes.Equal(got, want) {
		t.Fatalf("Encoder() = %x\nwant      = %x", got, want)
	}
}
